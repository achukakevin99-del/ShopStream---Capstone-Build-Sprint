-- V1: core tables. Tenant-owned tables carry tenant_id and use composite FKs
-- so a row can never reference another tenant's data.
CREATE EXTENSION IF NOT EXISTS pgcrypto;   -- bcrypt hashing (crypt / gen_salt)
CREATE EXTENSION IF NOT EXISTS pg_trgm;    -- fast partial-text search (V2)

CREATE TABLE tenants (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       text        NOT NULL,
    slug       text        NOT NULL UNIQUE,
    currency   char(3)     NOT NULL DEFAULT 'KES',
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE users (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id     bigint      NOT NULL REFERENCES tenants(id),
    email         text        NOT NULL,
    password_hash text        NOT NULL,
    full_name     text        NOT NULL,
    role          text        NOT NULL DEFAULT 'customer'
                  CHECK (role IN ('owner','staff','customer')),
    created_at    timestamptz NOT NULL DEFAULT now(),
    UNIQUE (tenant_id, email),
    UNIQUE (tenant_id, id)
);

CREATE TABLE categories (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id  bigint NOT NULL REFERENCES tenants(id),
    parent_id  bigint,
    name       text   NOT NULL,
    UNIQUE (tenant_id, id),
    UNIQUE (tenant_id, name),
    FOREIGN KEY (tenant_id, parent_id) REFERENCES categories (tenant_id, id)
);

CREATE TABLE products (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id   bigint      NOT NULL REFERENCES tenants(id),
    category_id bigint,
    sku         text        NOT NULL,
    name        text        NOT NULL,
    description text,
    price_cents integer     NOT NULL CHECK (price_cents >= 0),
    stock       integer     NOT NULL DEFAULT 0 CHECK (stock >= 0),
    active      boolean     NOT NULL DEFAULT true,
    created_at  timestamptz NOT NULL DEFAULT now(),
    UNIQUE (tenant_id, sku),
    UNIQUE (tenant_id, id),
    FOREIGN KEY (tenant_id, category_id) REFERENCES categories (tenant_id, id)
);

CREATE TABLE orders (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id   bigint      NOT NULL REFERENCES tenants(id),
    user_id     bigint      NOT NULL,
    status      text        NOT NULL DEFAULT 'pending'
                CHECK (status IN ('pending','paid','shipped','delivered','cancelled')),
    total_cents bigint      NOT NULL DEFAULT 0 CHECK (total_cents >= 0),
    placed_at   timestamptz NOT NULL DEFAULT now(),
    UNIQUE (tenant_id, id),
    FOREIGN KEY (tenant_id, user_id) REFERENCES users (tenant_id, id)
);

CREATE TABLE order_items (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id        bigint  NOT NULL REFERENCES tenants(id),
    order_id         bigint  NOT NULL,
    product_id       bigint  NOT NULL,
    quantity         integer NOT NULL CHECK (quantity > 0),
    unit_price_cents integer NOT NULL CHECK (unit_price_cents >= 0),  -- price snapshot
    FOREIGN KEY (tenant_id, order_id)   REFERENCES orders   (tenant_id, id) ON DELETE CASCADE,
    FOREIGN KEY (tenant_id, product_id) REFERENCES products (tenant_id, id)
);

CREATE TABLE payments (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id    bigint      NOT NULL REFERENCES tenants(id),
    order_id     bigint      NOT NULL,
    method       text        NOT NULL CHECK (method IN ('card','mpesa','cash')),
    status       text        NOT NULL DEFAULT 'pending'
                 CHECK (status IN ('pending','paid','failed','refunded')),
    amount_cents bigint      NOT NULL CHECK (amount_cents >= 0),
    provider_ref text,                       -- gateway token only, never card numbers
    paid_at      timestamptz,
    FOREIGN KEY (tenant_id, order_id) REFERENCES orders (tenant_id, id)
);

CREATE TABLE audit_log (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id  bigint,
    table_name text        NOT NULL,
    record_id  bigint,
    action     text        NOT NULL CHECK (action IN ('INSERT','UPDATE','DELETE')),
    old_data   jsonb,
    new_data   jsonb,
    changed_by bigint,
    changed_at timestamptz NOT NULL DEFAULT now()
);
